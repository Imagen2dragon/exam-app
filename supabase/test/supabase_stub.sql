-- Minimal stand-ins for what Supabase provides, to test setup.sql's syntax and policy logic.
create role authenticated; create role anon;
create schema auth; create schema storage;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
create table storage.buckets (id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
create table storage.objects (id serial primary key, bucket_id text, name text, owner uuid);
create function storage.foldername(name text) returns text[] language sql immutable as $$ select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'), 1) - 1] $$;
alter table storage.objects enable row level security;
grant usage on schema storage, auth to authenticated, anon;
grant all on storage.objects to authenticated, anon; grant usage on sequence storage.objects_id_seq to authenticated, anon;
